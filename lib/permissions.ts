export type PermissionMatrix = Record<StaffRole, Capability[]>;

export function hasCapability(matrix: PermissionMatrix, role: StaffRole, capability: Capability): boolean {
  return matrix[role]?.includes(capability) ?? false;
}

/** Route prefix → capability required to open it. Longest prefix wins. */
export const ROUTE_CAPABILITIES: { prefix: string; capability: Capability }[] = [
  { prefix: "/dashboard", capability: "dashboard.view" },
  { prefix: "/waiting-list", capability: "waiting.view" },
  { prefix: "/patients/new", capability: "patients.create" },
  { prefix: "/patients", capability: "patients.view" },
  { prefix: "/counselling", capability: "counselling.view" },
  { prefix: "/donors", capability: "donors.view" },
  { prefix: "/surrogates", capability: "surrogates.view" },
  { prefix: "/embryology", capability: "embryology.view" },
  { prefix: "/pharmacy", capability: "pharmacy.view" },
  { prefix: "/billing", capability: "billing.view" },
  { prefix: "/accounts", capability: "wallets.view" },
  { prefix: "/reports", capability: "reports.view" },
  { prefix: "/requests", capability: "requests.create" },
  { prefix: "/admin", capability: "admin.view" },
];

export function capabilityForPath(pathname: string): Capability | null {
  const match = ROUTE_CAPABILITIES.filter((r) => pathname === r.prefix || pathname.startsWith(`${r.prefix}/`)).sort(
    (a, b) => b.prefix.length - a.prefix.length,
  )[0];
  return match?.capability ?? null;
}

